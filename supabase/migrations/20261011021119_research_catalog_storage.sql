-- Batch evidence stays private. Only explicitly published immutable versions are public.
create schema if not exists research_internal;
revoke all on schema research_internal from public, anon, authenticated;
grant usage on schema research_internal to service_role;

create table research_internal.batch_runs (
  id text primary key,
  completed_at timestamptz not null,
  requested integer not null check (requested > 0),
  selected integer not null check (selected >= 0),
  artifact_sha256 text not null check (artifact_sha256 ~ '^[a-f0-9]{64}$'),
  summary jsonb not null check (jsonb_typeof(summary) = 'object')
);
create table research_internal.papers (
  pmid text primary key check (pmid ~ '^[0-9]+$'),
  pmcid text,
  title text not null,
  doi text,
  source_url text,
  metadata jsonb not null check (jsonb_typeof(metadata) = 'object')
);
create table research_internal.protocol_candidates (
  run_id text not null references research_internal.batch_runs(id),
  pmid text not null references research_internal.papers(pmid),
  source_sha256 text check (source_sha256 ~ '^[a-f0-9]{64}$'),
  status text not null check (status in ('awaiting_human_review', 'source_fetch_failed')),
  evidence jsonb not null,
  review jsonb not null,
  gate jsonb not null,
  primary key (run_id, pmid),
  check (coalesce((gate->>'protocol_publishable')::boolean, false) = false),
  check (coalesce((gate->>'chart_publishable')::boolean, false) = false)
);
create index protocol_candidates_pmid_idx on research_internal.protocol_candidates(pmid);
alter table research_internal.batch_runs enable row level security;
alter table research_internal.papers enable row level security;
alter table research_internal.protocol_candidates enable row level security;
revoke all on all tables in schema research_internal from public, anon, authenticated;
grant select, insert, update on all tables in schema research_internal to service_role;

-- Published entries are not generated by the discovery/import job.
create table public.research_protocol_versions (
  id text not null,
  version integer not null check (version > 0),
  release_id uuid not null unique,
  source_sha256 text not null check (source_sha256 ~ '^[a-f0-9]{64}$'),
  source_url text not null check (source_url like 'https://%'),
  reviewer_id text not null check (length(reviewer_id) > 0),
  reviewed_at timestamptz not null,
  published_at timestamptz not null default now(),
  status text not null check (status in ('PUBLISHED_PROTOCOL', 'REVOKED')),
  payload jsonb not null,
  primary key (id, version),
  check (payload->>'id' = id),
  check ((payload->>'version')::integer = version),
  check (payload->>'source_type' = 'RESEARCH'),
  check (payload->>'source_sha256' = source_sha256),
  check (payload->>'release_id' = release_id::text),
  check (payload->>'status' = 'PUBLISHED_PROTOCOL'),
  check (payload->>'runnable' = 'true'),
  check (jsonb_typeof(payload->'sessions') = 'array' and jsonb_array_length(payload->'sessions') > 0),
  check (payload ?& array['id','version','source_type','source_sha256','release_id','status','runnable','sessions','title','description'])
);
alter table public.research_protocol_versions enable row level security;
revoke all on public.research_protocol_versions from public, anon, authenticated;
grant select on public.research_protocol_versions to anon, authenticated;
grant select, insert, update on public.research_protocol_versions to service_role;
create policy published_protocol_read on public.research_protocol_versions
  for select to anon, authenticated using (status = 'PUBLISHED_PROTOCOL');
create index research_protocol_published_idx on public.research_protocol_versions(published_at desc)
  where status = 'PUBLISHED_PROTOCOL';

create table public.research_catalog_state (
  id boolean primary key default true check (id = true),
  last_batch_id text not null references research_internal.batch_runs(id),
  checked_at timestamptz not null,
  requested integer not null check (requested > 0),
  candidates integer not null check (candidates >= 0),
  awaiting_review integer not null check (awaiting_review >= 0)
);
alter table public.research_catalog_state enable row level security;
revoke all on public.research_catalog_state from public, anon, authenticated;
grant select on public.research_catalog_state to anon, authenticated;
grant select, insert, update on public.research_catalog_state to service_role;
create policy catalog_state_read on public.research_catalog_state for select to anon, authenticated using (true);

create function public.research_catalog() returns jsonb
language sql stable security invoker set search_path = '' as $$
  select jsonb_build_object(
    'schema_version', 1,
    'items', coalesce((select jsonb_agg(p.payload order by p.published_at desc, p.id, p.version)
                      from public.research_protocol_versions p where p.status = 'PUBLISHED_PROTOCOL'), '[]'::jsonb),
    'metadata', (select jsonb_build_object('last_batch_id', s.last_batch_id,
                  'checked_at', s.checked_at, 'requested', s.requested,
                  'candidates', s.candidates, 'awaiting_review', s.awaiting_review)
                 from public.research_catalog_state s where s.id = true)
  );
$$;
revoke all on function public.research_catalog() from public;
grant execute on function public.research_catalog() to anon, authenticated, service_role;
comment on function public.research_catalog() is 'Public read-only catalog. Invoker rights and RLS; no research candidate is executable.';
